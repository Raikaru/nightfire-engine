std::vector<CreditRow> load_credits(const Elf32& action_elf, const StringTable& strings) {
    std::vector<CreditRow> rows;
    for (const CreditRowSrc& r : kCreditRows) rows.push_back({resolve(action_elf, strings, r.a), resolve(action_elf, strings, r.b), r.span});
    return rows;
}

