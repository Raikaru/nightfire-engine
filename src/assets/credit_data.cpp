std::string resolve(const Elf32& elf, const StringTable& strings, std::uint32_t v) {
    if (v == kNoText) return {};
    if (v >= 0x30000000) {
        const Bytes bytes = elf.at(v, 256);
        std::string out;
        for (std::uint8_t b : bytes) {
            if (b == 0) break;
            out.push_back(char(b));
        }
        if (out.size() == 256) throw FormatError("unterminated credit string");
        return out;
    }
    return std::string(strings.label(v));
}

