def text_size(text, small=False, bold=True):
    font = SMALL if small else BIG
    if not text:
        return 0, 0
    w = sum(len(font[c][0]) for c in text) + (len(text) - 1)
    if bold and not small:
        w += 1
    return w, len(font[text[0]])


def draw_text(img, x, y, text, ink, edge, small=False, bold=True, put=None):
    """Draws `text`; bold lettering puts the extra left-hand texels in the edge colour, like the original."""
    font = SMALL if small else BIG
    cx = x
    for c in text:
        rows = font[c]
        for j, row in enumerate(rows):
            for i, bit in enumerate(row):
                if bit != "1":
                    continue
                if bold and not small:
                    put(img, cx + i, y + j, edge)
                    put(img, cx + i + 1, y + j, ink)
                else:
                    put(img, cx + i, y + j, ink)
        cx += len(rows[0]) + 1
    # A bold texel can land on the edge colour of the next column: repaint the ink pass last.
    if bold and not small:
        cx = x
        for c in text:
            rows = font[c]
            for j, row in enumerate(rows):
                for i, bit in enumerate(row):
                    if bit == "1":
                        put(img, cx + i + 1, y + j, ink)
            cx += len(rows[0]) + 1
